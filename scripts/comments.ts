import { readFileSync } from 'node:fs';
import { extname, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { cssComments, hashComments, htmlComments } from './comments-text.ts';
import type { CommentHit } from './comments-hit.ts';
import { jsComments } from './comments-js.ts';
import { repoRoot } from './root.ts';
import { walk } from './walk.ts';

const JS = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.vue']);
const CSS = new Set(['.css', '.scss']);
const HTML = new Set(['.html', '.htm']);
const HASH = new Set(['.yml', '.yaml']);

export function violationsIn(fileName: string, text: string): string[] {
  if (generated(text)) return [];
  const base = fileName.slice(fileName.lastIndexOf('/') + 1);
  const ext = extname(fileName);
  const comments = JS.has(ext)
    ? jsComments(text)
    : CSS.has(ext)
      ? cssComments(text)
      : HTML.has(ext)
        ? htmlComments(text)
        : HASH.has(ext) || base === '.env.example'
          ? hashComments(text)
          : null;
  if (!comments) return [];
  const licensed = licenseSet(text, comments);
  const out: string[] = [];
  for (const comment of comments) {
    if (licensed.has(comment) || directive(comment.text)) continue;
    out.push(`${comment.line}: ${comment.text.trim().slice(0, 80)}`);
  }
  return out;
}

export function scanRepo(root: string): string[] {
  const problems: string[] = [];
  for (const file of walk(root)) {
    const rel = relative(root, file);
    const text = readFileSync(file, 'utf8');
    for (const hit of violationsIn(rel, text)) problems.push(`${rel}:${hit}`);
  }
  return problems;
}

function generated(text: string): boolean {
  return /@generated\b|DO NOT EDIT|Code generated by/i.test(
    text.split('\n').slice(0, 30).join('\n'),
  );
}

function directive(body: string): boolean {
  const text = body
    .replace(/^\s*\*\s?/gm, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const ts = /^@ts-(?:expect-error|ignore|nocheck)\s+(\S(?:.*\S)?)$/.exec(text);
  if (ts?.[1] && ts[1].length >= 3) return true;
  const reason =
    /^(?:eslint-disable(?:-next-line|-line)?|eslint-enable|prettier-ignore|biome-ignore|(?:istanbul|c8|v8) ignore\b|@[A-Za-z][\w-]*)\b.*\s--\s+(\S(?:.*\S)?)$/.exec(
      text,
    );
  return Boolean(reason?.[1] && reason[1].length >= 3);
}

function licenseSet(text: string, comments: CommentHit[]): Set<CommentHit> {
  const ok = new Set<CommentHit>();
  let cursor = 0;
  for (const comment of comments) {
    if (text.slice(cursor, comment.start).trim() !== '') break;
    if (!/copyright|spdx-license-identifier|\blicense\b/i.test(comment.text)) break;
    ok.add(comment);
    cursor = comment.end;
  }
  return ok;
}

function main(): void {
  const problems = scanRepo(repoRoot());
  for (const problem of problems) console.error(problem);
  if (problems.length === 0) console.log('comments: ok');
  process.exitCode = problems.length === 0 ? 0 : 1;
}

const entry = process.argv[1];
if (entry && import.meta.url === pathToFileURL(entry).href) main();
