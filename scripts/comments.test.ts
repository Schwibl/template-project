import { describe, expect, it } from 'vitest';
import { scanRepo, violationsIn } from './comments.ts';
import { repoRoot } from './root.ts';

const urlLine = "const baseURL = process.env.E2E_BASE_URL ?? 'http://localhost:4173';";
const page = [
  'const html = `',
  '  <h1>${import.meta.env.VITE_APP_TITLE ?? "Template project"}</h1>',
  '`;',
].join('\n');

describe('comment check', () => {
  it('flags a plain comment and allows a directive with a reason', () => {
    expect(violationsIn('a.ts', 'export const n = 1;\n// hello\n')).toEqual(['2: hello']);
    expect(
      violationsIn(
        'a.ts',
        '// eslint-disable-next-line eqeqeq -- fixture uses ==\nexport const n = 1;\n',
      ),
    ).toEqual([]);
    expect(
      violationsIn('a.ts', '// eslint-disable-next-line eqeqeq\nexport const n = 1;\n'),
    ).toEqual(['1: eslint-disable-next-line eqeqeq']);
    expect(
      violationsIn(
        'a.ts',
        '// @ts-expect-error legacy types omit this field\nexport const n = 1;\n',
      ),
    ).toEqual([]);
  });

  it('allows a license header, a shebang, and a generated file', () => {
    const licensed =
      '// Copyright (c) 2026 Example\n// SPDX-License-Identifier: MIT\nexport const n = 1;\n';
    expect(violationsIn('a.ts', licensed)).toEqual([]);
    expect(violationsIn('a.ts', '#!/usr/bin/env node\nexport const n = 1;\n')).toEqual([]);
    expect(violationsIn('a.ts', '// @generated by tool\n// hello\n')).toEqual([]);
  });

  it('ignores comment markers inside strings and flags hash and html comments', () => {
    expect(violationsIn('playwright.config.ts', urlLine)).toEqual([]);
    expect(violationsIn('main.ts', page)).toEqual([]);
    expect(violationsIn('.env.example', 'KEY=1\n# note\n')).toEqual(['2: note']);
    expect(violationsIn('a.yml', 'name: "a # b"\n')).toEqual([]);
    expect(violationsIn('index.html', '<!-- note -->\n')).toEqual(['1: note']);
  });

  it('finds no comments in this repo', () => {
    expect(scanRepo(repoRoot())).toEqual([]);
  });
});
